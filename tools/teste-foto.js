var F = require('../js/foto-nucleo.js');
var ok = 0, falhas = 0;
function t(nome, cond) { if (cond) ok++; else { falhas++; console.log('  FALHA ' + nome); } }
var HJ = '2026-10-30';
t('data DD/MM/AAAA', F.data('12/11/2026', HJ) === '2026-11-12');
t('data DD/MM/AA', F.data('05/01/27', HJ) === '2027-01-05');
t('data DD/MM sem ano usa ano atual', F.data('12/11', HJ) === '2026-11-12');
t('data DD/MM já passada há muito vai p/ ano seguinte', F.data('05/01', HJ) === '2027-01-05');
t('data inválida', F.data('31/02/2026', HJ) === '' && F.data('abc', HJ) === '' && F.data('', HJ) === '');
t('data com texto em volta', F.data('Vencimento: 12/11/2026', HJ) === '2026-11-12');
t('preço R$ 9,39', F.preco('R$ 9,39') === 9.39);
t('preço 1.234,56', F.preco('1.234,56') === 1234.56);
t('preço número', F.preco(12.5) === 12.5);
t('preço vazio', F.preco('') === null && F.preco('grátis') === null);
t('hora', F.hora('14h30') === '14:30' && F.hora('9:05') === '09:05' && F.hora('25:00') === '');
var n = F.normalizar({ destino: 'compras', nome: 'Coxa e sobrecoxa', preco: 'R$ 9,39', unidade: 'kg', local: 'Atacadão' }, HJ);
t('normaliza compras', n.destino === 'compras' && n.nome === 'Coxa e sobrecoxa' && n.preco === 9.39 && n.local === 'Atacadão' && n.unidade === 'kg');
n = F.normalizar({ destino: 'xyz', titulo: 'Pagar boleto', data: '12/11/2026', valor: '150,00' }, HJ);
t('destino inválido vira tarefa', n.destino === 'tarefa' && n.data === '2026-11-12' && n.valor === 150);
n = F.normalizar(null, HJ);
t('normaliza nulo', n.destino === 'tarefa' && n.titulo === '' && n.preco === null);
var c = F.paraCompra({ nome: '  Arroz ', preco: 22.9, unidade: 'pct', local: 'Atacadão' }, 'id1');
t('item de compra', c.id === 'id1' && c.nome === 'Arroz' && c.preco === 22.9 && c.comprado === false && Object.keys(c).sort().join() === 'comprado,id,local,nome,preco,unidade');
var tr = F.paraTarefa({ titulo: 'Pagar boleto Enel', data: '2026-11-12', valor: 150 }, 'id2', 'Casa');
t('tarefa', tr.titulo === 'Pagar boleto Enel (R$ 150,00)' && tr.vence === '2026-11-12' && tr.lista === 'Casa' && tr.prio === 'media' && !tr.feita);
var cp = F.paraCompromisso({ titulo: 'Consulta', data: '2026-11-12', hora: '14:30', local: 'Clínica' }, 'id3');
t('compromisso', cp.data === '2026-11-12' && cp.hora === '14:30' && cp.local === 'Clínica' && cp.fonte === 'manual');
t('compromisso sem data é nulo', F.paraCompromisso({ titulo: 'x', data: '' }, 'i') === null);
var d = F.dimensoes(4000, 3000, 1280);
t('reduz maior lado a 1280', d.w === 1280 && d.h === 960);
d = F.dimensoes(800, 600, 1280);
t('não amplia', d.w === 800 && d.h === 600);
d = F.dimensoes(1000, 3000, 1280);
t('retrato', d.h === 1280 && d.w === 427);
n = F.normalizar({ destino: 'agenda', titulo: 'Boleto Bancário', data: '12/11/2026', hora: '10:00', valor: 'R$ 187,45' }, HJ);
t('boleto nunca vai para agenda', n.destino === 'tarefa' && n.data === '2026-11-12' && n.valor === 187.45);
n = F.normalizar({ destino: 'compras', nome: 'Coxa', preco: '9,39', local: 'loja', titulo: 'Atacadão', hora: '00:00' }, HJ);
t('local genérico usa o nome da loja do título', n.local === 'Atacadão');
t('hora 00:00 é descartada', n.hora === '');
n = F.normalizar({ destino: 'compras', nome: 'Arroz', local: 'mercado' }, HJ);
t('local genérico fica vazio', n.local === '');
var N = require('../js/sync-nucleo.js');
t('compras é coleção sincronizada', N.COLECOES.indexOf('compras') >= 0 && /^[a-z]{2,16}$/.test('compras'));
var fsS = require('fs').readFileSync;
var sw = fsS(__dirname + '/../sw.js', 'utf8');
t('sw guarda o código da foto', /js\/foto-nucleo\.js/.test(sw) && /js\/foto\.js/.test(sw));
t('sw não guarda imagens enviadas (só GET do próprio site)', !/\/foto['"]/.test(sw));
