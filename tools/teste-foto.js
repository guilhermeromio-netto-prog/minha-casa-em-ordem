t('store saneia compras', /s\.compras = arr\(o\.compras\)/.test(st));
t('sync conta compras como dado próprio', /'compras'/.test(fsS(__dirname + '/../js/sync.js', 'utf8')));
console.log(ok + ' ok, ' + falhas + ' falhas'); process.exit(falhas ? 1 : 0);
